#!/usr/bin/env bash
# The generated /workspaces/AGENTS.md (docs/remote-workspace.md, "Workspace AGENTS.md"): written only in a remote
# workspace, from the repository list and the inventory data, idempotent, replaces stale content, never leaks a hostname,
# an address or a token (the repository is public), and fails the render when a cloned repository has no description.
# No network.
. "$(dirname "$0")/lib.sh"

SCRIPT="home/.chezmoiscripts/workspace/run_onchange_after_210-workspace-agents-md.sh.tmpl"
REPOS="$AI_ROOT/home/.chezmoidata/remote-workspace.yaml"
INV="$AI_ROOT/home/.chezmoidata/workspace-inventory.yaml"

# 1. flag unset: the script renders to nothing, so chezmoi skips it
out=$(render legacy-devcontainer "$SCRIPT") || _fail "render, flag unset"
[ -z "$(printf '%s' "$out" | tr -d '[:space:]')" ] || _fail "the script must render to nothing with the flag unset"

# 2. flag set: the script writes the file
T=$(new_tmp)
mkdir -p "$T/root"
out=$(render remote-workspace-linux "$SCRIPT") || _fail "render, flag set"
printf '%s\n' "$out" | sed "s|^root=.*|root=\"$T/root\"|" > "$T/run.sh"
assert_contains "script root is the workspace root" "$out" 'root="/workspaces"'
bash -n "$T/run.sh" || _fail "the rendered script has a syntax error"
res=$(bash "$T/run.sh" 2>&1); rc=$?
assert_eq "script exits 0" "$rc" "0"
assert_contains "script reports the write" "$res" "wrote $T/root/AGENTS.md"
F="$T/root/AGENTS.md"
[ -s "$F" ] || _fail "AGENTS.md was not written"
body=$(cat "$F")
assert_contains "marked as generated" "$body" "Generated by chezmoi from mmalyska/dotfiles"
assert_contains "has the title" "$body" "# Workspace context"

# 3. every cloned repository and every other repository is in the file
n=0
while IFS= read -r repo; do
    name=${repo##*/}
    assert_contains "cloned repository $name listed" "$body" "### \`/workspaces/$name\` ($repo)"
    n=$((n + 1))
done < <(sed -n 's/^    - \(.*\)$/\1/p' "$REPOS")
[ "$n" -ge 1 ] || _fail "the repository list is empty"
assert_eq "one section per cloned repository" "$(printf '%s\n' "$body" | grep -c '^### `/workspaces/')" "$n"
assert_contains "the Jetson fork is cloned and described" "$body" "talos-jetson-orin"
m=0
while IFS= read -r name; do
    assert_contains "other repository $name listed" "$body" "- \`$name\`:"
    m=$((m + 1))
done < <(sed -n 's/^    - name: \(.*\)$/\1/p' "$INV")
[ "$m" -ge 1 ] || _fail "the list of other repositories is empty"

# 4. a public file: no private domain, address, token, key or private repository name
for bad in "mmalyska.cloud" "192.168." "10.244." "ghp_" "github_pat_" "PRIVATE KEY" "BEGIN OPENSSH" "homeinfra" "k8s-deployments" "<secret:"; do
    assert_not_contains "no $bad in the generated file" "$body" "$bad"
done
assert_not_contains "no hostname in the repository data" "$(cat "$INV")" "mmalyska.cloud"

# 5. it stays small enough to load at the start of every session
size=$(wc -c < "$F" | tr -d ' ')
[ "$size" -lt 16384 ] || _fail "the generated file is $size bytes, over the 16 KB budget"

# 6. the sections an agent needs are there
for h in "## Environment" "## Persistence" "## Repositories" "## What this workspace can and cannot do" "## Secrets and credentials" "## Working conventions"; do
    assert_contains "section $h" "$body" "$h"
done

# 7. a second run changes nothing and says so
sum1=$(sha256sum "$F" | cut -d' ' -f1)
res=$(bash "$T/run.sh" 2>&1)
assert_contains "second run reports up to date" "$res" "up to date"
assert_eq "second run leaves the file as it was" "$(sha256sum "$F" | cut -d' ' -f1)" "$sum1"

# 8. stale or hand-edited content is replaced, and no temporary file is left behind
printf 'stale local edit\n' > "$F"
res=$(bash "$T/run.sh" 2>&1)
assert_contains "stale content reported as a write" "$res" "wrote $F"
assert_eq "stale content replaced" "$(sha256sum "$F" | cut -d' ' -f1)" "$sum1"
assert_contains "the hand-written file was kept once" "$res" "kept the previous file as $T/root/AGENTS.md.pre-chezmoi"
assert_eq "the kept copy is the hand-written file" "$(cat "$T/root/AGENTS.md.pre-chezmoi")" "stale local edit"
printf 'a second hand edit\n' > "$F"
res=$(bash "$T/run.sh" 2>&1)
assert_not_contains "a later edit does not replace the kept copy" "$res" "kept the previous file"
assert_eq "the first kept copy survives" "$(cat "$T/root/AGENTS.md.pre-chezmoi")" "stale local edit"
assert_eq "the generated file is back" "$(sha256sum "$F" | cut -d' ' -f1)" "$sum1"
left=$(find "$T/root" -name '.AGENTS.md.*' | head -1)
[ -z "$left" ] || _fail "a temporary file was left behind: $left"
mode=$(stat -c '%a' "$F" 2>/dev/null || stat -f '%Lp' "$F")
assert_eq "file mode is 644" "$mode" "644"

# 9. a cloned repository without a description fails the render, so the inventory cannot drift from the clone list
SRC="$T/src"; mkdir -p "$SRC"
rsync -a --exclude .git --exclude .worktrees "$AI_ROOT/" "$SRC/"
while IFS= read -r line; do
    printf '%s\n' "$line"
    [ "$line" = "    - mmalyska/dotfiles" ] && printf '%s\n' "    - someone/unlisted"
done < "$REPOS" > "$SRC/home/.chezmoidata/remote-workspace.yaml"
grep -q 'someone/unlisted' "$SRC/home/.chezmoidata/remote-workspace.yaml" || _fail "test setup: the extra repository was not added"
if err=$(chezmoi --source "$SRC" --config "$FIXTURES/remote-workspace-linux.toml" execute-template \
        < "$SRC/$SCRIPT" 2>&1 >/dev/null); then
    _fail "the render must fail when a cloned repository has no inventory entry"
fi
assert_contains "the failure names the repository" "$err" "no entry for unlisted"
